"""Validate and normalize catalog data before generating a release or import."""
from argparse import ArgumentParser
import json
from pathlib import Path
import re
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "etl" / "fragrances.json"
SEED = ROOT / "database" / "migrations" / "V002__seed_catalog.sql"
MOODS = {"angelic", "joyful", "mysterious", "cozy", "candy-like", "forest-like"}
FAMILIES = {"Floral", "Gourmand", "Woody", "Fresh", "Amber / Spiced"}
SEASONS = {"Spring", "Summer", "Autumn", "Winter", "Year-round"}
TIMES = {"Day", "Evening"}
FIELDS = {"id", "name", "brand", "notes", "accords", "moods", "family", "seasons", "times", "source_url"}


def clean_text(value):
    if not isinstance(value, str):
        raise ValueError("Text values must be strings")
    result = " ".join(value.split())
    if not result or not result.isprintable():
        raise ValueError("Expected printable, nonempty text")
    return result


def clean_list(value, allowed=None, *, required=False):
    if not isinstance(value, list) or (required and not value):
        raise ValueError("Expected a list" + (" with at least one entry" if required else ""))
    result = list({text.casefold(): text for text in map(clean_text, value)}.values())
    if allowed is not None and not set(result) <= allowed:
        raise ValueError(f"Unsupported labels: {set(result) - allowed}")
    return result


def normalize(records):
    if not isinstance(records, list) or not records:
        raise ValueError("Catalog must be a nonempty array")
    seen_ids = set()
    seen_names = set()
    canonical_notes = {}
    result = []
    for number, row in enumerate(records, 1):
        try:
            if not isinstance(row, dict) or row.keys() != FIELDS:
                raise ValueError("Expected exactly the catalog fields")
            record = {key: clean_text(row[key]) for key in ("id", "name", "brand", "family", "source_url")}
            if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", record["id"]):
                raise ValueError("ID must be a lowercase slug")
            identity = (record["brand"].casefold(), record["name"].casefold())
            if record["id"] in seen_ids or identity in seen_names:
                raise ValueError("Duplicate ID or brand and name")
            source = urlsplit(record["source_url"])
            if source.scheme != "https" or not source.hostname or source.username or any(c.isspace() for c in record["source_url"]):
                raise ValueError("Source must be a public HTTPS product page")
            if record["family"] not in FAMILIES:
                raise ValueError("Unsupported fragrance family")
            record["notes"] = clean_list(row["notes"], required=True)
            if any("," in note for note in record["notes"]):
                raise ValueError("Note labels cannot contain commas")
            record["notes"] = [canonical_notes.setdefault(note.casefold(), note) for note in record["notes"]]
            record["accords"] = clean_list(row["accords"])
            record["moods"] = clean_list(row["moods"], MOODS)
            record["seasons"] = clean_list(row["seasons"], SEASONS, required=True)
            if "Year-round" in record["seasons"] and len(record["seasons"]) > 1:
                raise ValueError("Year-round must be the only season when selected")
            record["times"] = clean_list(row["times"], TIMES, required=True)
            seen_ids.add(record["id"])
            seen_names.add(identity)
            result.append(record)
        except ValueError as error:
            raise ValueError(f"Record {number}: {error}") from error
    return sorted(result, key=lambda record: record["id"])


def snapshot(records):
    return json.dumps(records, indent=2, ensure_ascii=False) + "\n"


def import_sql(records):
    payload = snapshot(records)
    delimiter = "$scent_catalog$"
    while delimiter in payload:
        delimiter = delimiter[:-1] + "_$"
    return f"""-- Generated by etl/catalog.py
LOCK TABLE fragrance IN SHARE ROW EXCLUSIVE MODE;
UPDATE fragrance SET active = false WHERE active;
INSERT INTO fragrance (id, name, brand, notes, accords, moods, family, seasons, times, source_url, active)
SELECT id, name, brand, notes, accords, moods, family, seasons, times, source_url, true
FROM jsonb_to_recordset({delimiter}
{payload}{delimiter}::jsonb) AS source(
    id text, name text, brand text, notes text[], accords text[], moods text[],
    family text, seasons text[], times text[], source_url text
)
ON CONFLICT (id) DO UPDATE SET
    name = excluded.name, brand = excluded.brand, notes = excluded.notes, accords = excluded.accords,
    moods = excluded.moods, family = excluded.family, seasons = excluded.seasons, times = excluded.times,
    source_url = excluded.source_url, active = true;
"""


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=INPUT)
    parser.add_argument("--output", type=Path, help="Write a normalized JSON artifact")
    parser.add_argument("--sql-output", type=Path, help="Write import SQL for psql --single-transaction")
    parser.add_argument("--check-seed", action="store_true", help="Check the first-release seed migration")
    args = parser.parse_args()
    try:
        records = normalize(json.loads(args.input.read_text(encoding="utf-8")))
        if args.check_seed and SEED.read_text(encoding="utf-8") != import_sql(records):
            raise ValueError("The first-release seed differs from the input catalog")
        if args.output:
            args.output.write_text(snapshot(records), encoding="utf-8", newline="\n")
        if args.sql_output:
            args.sql_output.write_text(import_sql(records), encoding="utf-8", newline="\n")
    except (OSError, ValueError) as error:
        parser.exit(1, f"Catalog validation failed. {error}\n")
    print(f"Validated {len(records)} fragrances")


if __name__ == "__main__":
    main()

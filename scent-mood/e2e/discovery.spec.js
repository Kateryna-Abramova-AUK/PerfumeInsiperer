import { expect, test } from '@playwright/test'

test('posts Mysterious + Cherry + Evening and explains the result in the browser', async ({ page, browser }) => {
  await page.goto('/')
  await page.getByRole('link', { name: 'Explore scents' }).click()
  await page.getByRole('button', { name: /Mysterious/ }).click()
  await page.getByRole('button', { name: /Cozy/ }).click()
  await page.getByRole('button', { name: /Joyful/ }).click()
  await expect(page.getByRole('button', { name: /Joyful/ })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: /Cozy/ }).click()
  await page.getByLabel('Preferred note').selectOption('Cherry')
  await page.getByLabel('Time of day').selectOption('Evening')
  const sent = page.waitForRequest(request =>
    request.url().endsWith('/api/recommendations') && request.method() === 'POST')
  await page.getByRole('button', { name: 'Find fragrances' }).click()
  expect((await sent).postDataJSON()).toEqual({
    moods: ['mysterious'], preferredNote: 'Cherry', family: '', timeOfDay: 'Evening',
  })
  const results = page.getByRole('region', { name: 'Your recommendations' })
  await expect(results.getByRole('article')).toHaveCount(3)
  const first = results.getByRole('article').first()
  await expect(first.getByRole('heading', { name: 'Lost Cherry' })).toBeVisible()
  await expect(first).toContainText('Mysterious')
  await expect(first).toContainText(/contains Black Cherry/i)
  await expect(results).toContainText('Does not contain Cherry.')
  await expect(results.getByRole('heading', { name: 'Warm Cotton' })).toHaveCount(0)
  await expect(results.getByRole('heading', { name: 'Whipped Cherry' })).toHaveCount(0)
  const name = await first.getByRole('heading', { level: 3 }).innerText()
  await first.getByRole('button', { name: 'Save ' + name }).click()
  await expect(first.getByRole('button', { name: 'Remove ' + name })).toBeEnabled()
  await page.getByRole('link', { name: 'Shortlist', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()

  const other = await browser.newPage()
  try {
    await other.goto(new URL('/shortlist', page.url()).href)
    await expect(other.getByRole('link', { name: 'Browse catalog' })).toBeVisible()
  } finally {
    await other.close()
  }

  await page.getByRole('button', { name: 'Remove ' + name }).click()
  await expect(page.getByRole('link', { name: 'Browse catalog' })).toBeVisible()
})

test('combines catalog search with all selected notes and clears the filters', async ({ page }) => {
  await page.goto('/catalog')
  await expect(page.getByRole('article').first()).toBeVisible()
  await page.getByRole('searchbox', { name: 'Fragrance or brand' }).fill('iMaGiNaRy')
  await page.locator('summary').filter({ hasText: 'Filter by notes' }).click()
  await page.getByRole('searchbox', { name: 'Search notes' }).fill('berga')
  await page.getByRole('checkbox', { name: 'Bergamot', exact: true }).check()
  await page.getByRole('searchbox', { name: 'Search notes' }).fill('grape')
  await page.getByRole('checkbox', { name: 'Grapefruit', exact: true }).check()
  await page.getByLabel('Season').selectOption('Summer')
  await page.getByLabel('Time of day').selectOption('Evening')
  await page.getByRole('button', { name: 'Search catalog' }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(page.getByRole('heading', { name: 'Falling into the Sea' })).toBeVisible()
  await page.getByLabel('Fragrance family').selectOption('Gourmand')
  await page.getByRole('button', { name: 'Search catalog' }).click()
  await expect(page.getByText('No fragrances found.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await expect(page.getByRole('article').nth(4)).toBeVisible()

  await page.getByLabel('Season').selectOption('Winter')
  await page.getByLabel('Time of day').selectOption('Day')
  await page.getByRole('button', { name: 'Search catalog' }).click()
  await expect(page.getByRole('heading', { name: 'Warm Cotton' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Lost Cherry' })).toHaveCount(0)

  await page.getByRole('button', { name: 'Clear filters' }).click()
  await page.getByRole('searchbox', { name: 'Fragrance or brand' }).fill('lOsT')
  await page.getByRole('button', { name: 'Search catalog' }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(page.getByRole('heading', { name: 'Lost Cherry' })).toBeVisible()

  const exact = await page.request.get('/api/catalog', { params: { notes: 'black cherry' } })
  expect((await exact.json()).map(item => item.id)).toEqual(['lost-cherry'])
  const generic = await page.request.get('/api/catalog', { params: { notes: 'cherry' } })
  expect(await generic.json()).toEqual([])
})

test('recovers from an incompatible refinement and fits a narrow screen', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Find your scent' })).toBeVisible()
  await page.getByRole('link', { name: 'Explore scents' }).click()
  await page.getByRole('button', { name: /Mysterious/ }).click()
  await page.getByLabel('Fragrance family').selectOption('Floral')
  await page.getByLabel('Time of day').selectOption('Evening')
  await page.getByRole('button', { name: 'Find fragrances' }).click()
  await expect(page.getByText('No fragrances match these choices.')).toBeVisible()
  await page.getByRole('button', { name: 'Clear family filter' }).click()
  await expect(page.getByRole('article').first()).toBeVisible()
  await expect(page.getByLabel('Time of day')).toHaveValue('Evening')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})
